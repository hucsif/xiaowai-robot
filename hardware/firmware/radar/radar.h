#pragma once

#include <stdbool.h>
#include <stdint.h>

#include "radar_config.h"

/* 雷达采集模块对外接口（R60ABD1 60GHz 呼吸睡眠 + LD2450 24GHz 运动追踪）。
 *
 * 本模块只做「采集 + 解析 + 日志 + 状态上行」：初始化两路 UART，把原始字节喂给
 * 两个纯 C 解析器，按周期把解析结果打到串口，并用 radar_snapshot() 对外暴露一份
 * 实时快照。不含姿态/睡眠等业务状态机。
 *
 * 网络上报只做一件事（开关见 radar_config.h 的 DESKBOT_RADAR_UPLINK_ENABLE）：
 * 按 RADAR_UPLINK_INTERVAL_MS 把 radar_snapshot() 打包成一条 radar_state JSON
 * 交 ws_transport_enqueue_state() 上行（走主连接 /asr_chat）。方向是**单向**的
 * ——本模块只发不收，不解析任何服务端语义，也不做下行控制。
 * 上行本身【不触发任何对话轮次】：服务端收到后只写进按设备的缓存，等 LLM 调用
 * get_heart_rate / get_breath_rate / get_radar_position 工具时再读出来。
 *
 * 日志级别说明：本固件运行期日志级别固定为 WARN（log_info 是空操作），
 * 因此这里所有输出都用 log_warn，标签为 [RADAR] / [RADAR/R60] / [RADAR/LD2450]。
 */

/* ================================================================
 * 数据字段含义参考
 *
 * R60ABD1 的定义来自 caterpillar 项目的 radar_data_export.h ——
 * 「固件团队 ↔ 算法团队」的字段合约，已对照厂商 V1.3 协议核对；
 * LD2450 来自其串口协议与上游用法。
 *
 * 日志示例：
 *   [RADAR/R60]    ok=1066 bad=0 | presence=1 motion=1 move=2
 *                  pos=(x=8,y=46)cm breath=21 heart=74 bed=0 stage=3
 *   [RADAR/LD2450] ok=456 bad=0 | n=2 T0(x=12,y=145,v=-3) T1(x=-30,y=89,v=12)
 * ================================================================ */

/* ---- ok / bad：解析统计（本模块自加，不是雷达数据）----
 *   ok   累计成功解析的帧数（开机以来单调递增）
 *   bad  累计校验失败的帧数
 * 两个都是 0 → RX 上一个字节都没进来（查接线/供电）
 * bad 增长而 ok 不动 → 收到字节但校验不过（查波特率/共地）
 */

/* ---- R60ABD1（60GHz 呼吸/睡眠雷达）----
 * 字段       取值                                上报频率
 *   presence 0=无人 1=有人                        状态变化（无人→有人 <0.5s；有人→无人 ~40s）
 *   motion   0=无运动 1=静止 2=活动                状态变化（<0.5s）
 *   move     体动幅度 0~100                        每秒
 *   breath   呼吸率 0~35 次/分（0=无效）            每 3 秒
 *   heart    心率 60~120 次/分（0=无效）            每 3 秒
 *   bed      0=离床 1=在床                         状态变化（入床即时；离床 ~30s 后）
 *   stage    0=深睡 1=浅睡 2=清醒 3=无             每 10 分钟（仅入床状态有效）
 *   pos(x,y) 【已停用】DP5 解析已 #if 0 —— 位置改用 LD2450 的 10Hz 坐标
 *
 * move 分段语义：0~10 微动(呼吸级) / 11~30 小幅(写字翻书) /
 *                31~60 中幅(调整坐姿) / 61~100 大幅(起身挥手)
 *
 * stage 的 3=无 表示「离床/实时模式」—— 离床时读到 3 是正常的，不是异常值。
 *
 * pos(x,y) 用途：x 横向偏移、y 前方距离。典型用法是蹲下检测 ——
 *   体动幅度大但 x/y 几乎不变 = 原地蹲下；x/y 大幅变化则是「走开」，不算蹲下。
 *   ⚠️ 本板这个位置判据**改由 LD2450 提供**（R60 的 DP5 频率太低不够平滑）：
 *      体动来自 R60，位置来自 LD2450，两者在 radar.cpp 里汇合到同一个 squat FSM。
 *
 * 距离参考（判断摆放是否合理）：书桌 30~80cm；床头 50~150cm。
 */

/* ---- LD2450（24GHz 多目标运动追踪雷达）----
 * 帧固定 30B、上电即 10Hz 上报、最多 3 个目标、无校验和。
 *
 *   n        当前有效目标数（0~3）
 *   T0/T1/T2 第几个目标
 *   x        横向坐标（cm）—— 左负右正
 *   y        前方距离（cm）
 *   v        径向速度（cm/s），符号表示靠近/远离（建议实测确认正负方向）
 *
 * 用途参考：
 *   转头跟随 —— 用 atan2(x, y) 求水平方位角；上游做法会忽略 3m 以外的目标。
 *   挥手检测 —— 观察 x 的符号翻转配合速度变化。
 *
 * ⚠️ 本板已实现「说话时转向说话人」：ASR 识别成功后，服务端下发一个
 *    HEAD_SERVO_LOOK 模式位（角度由设备按上述方位角自己算），见 radar.cpp 的
 *    look_angle_provider()；LD2450 连续 DESKBOT_LOOK_RECENTER_QUIET_MS 看不见
 *    人则自动回中，见 maybe_recenter()。开关与阈值见 radar_config.h 的
 *    DESKBOT_LOOK_*。
 *    （触发信号曾用 ESP-SR VAD —— 噪音误触 + 快说漏触发；回中曾用 R60 的
 *      presence —— 上报延迟 ~40s，会拖到下一次对话才落地。两者均已弃用。）
 *
 * 注：日志里的 x/y 已由驱动的 mm 换算成 cm。
 */

/** 初始化两路雷达 UART + 解析器（幂等）。
 *  @return 始终 true（UART begin 无失败返回；接线问题由日志的排障提示暴露）。
 *          失败或未就绪时切勿调用 task_setup_radar()。 */
bool setup_radar();

/** 创建雷达采集任务（幂等）：10ms 轮询两路 UART，按 RADAR_LOG_INTERVAL_MS 输出摘要。 */
void task_setup_radar();

/* ================================================================
 * 实时快照（供上行与其它业务模块读取）
 * ================================================================ */

/** 雷达实时快照。
 *
 * ⚠️ 各字段是「各自最近一次解析结果」，**不是同一时刻的原子快照** —— 两路雷达
 *    上报频率差很多（心率/呼吸 3s 一帧、LD2450 10Hz），字段间有秒级时间差。
 *
 * 参考系：方位相对**机身正前方**（LD2450 固定装在身体/底座，不随舵机转动）。 */
typedef struct {
  bool    present;     /* LD2450 是否检到目标（运动追踪，人极静时可能丢） */
  int16_t x_mm;        /* 横向 mm；**负 = 机器人左侧**（已按 DESKBOT_RADAR_X_SIGN 规范化） */
  int16_t y_mm;        /* 前方距离 mm */
  uint8_t heart_rate;  /* R60 心率 次/分；0 = 未知（含超 RADAR_VITAL_TTL_MS 未更新） */
  uint8_t breath_rate; /* R60 呼吸率 次/分；0 = 未知 */
} radar_snapshot_t;

/** 取一份当前快照（值语义，不返回内部指针——避免把解析器状态泄给其它任务）。
 *  雷达未启动（setup_radar 未调用）时返回全零快照。 */
radar_snapshot_t radar_snapshot(void);
